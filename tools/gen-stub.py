#!/usr/bin/env python3
"""gen-stub.py <android-lib.so> <out.c>: a glibc-loadable stand-in with the same Java_*
exports. Each export jumps through a slot that JNI_OnLoad fills from the real library,
which pzldr loads from <stub dir>/android/<same name>."""
import subprocess, sys, re, os
lib, out = sys.argv[1], sys.argv[2]
syms = subprocess.run(['readelf', '-sW', '--dyn-syms', lib], capture_output=True, text=True, check=True).stdout
names = sorted({l.split()[7] for l in syms.splitlines()
                if len(l.split()) >= 8 and l.split()[6] != 'UND' and l.split()[3] == 'FUNC'
                and l.split()[7].startswith('Java_')})
has_onload = re.search(r'\sJNI_OnLoad$', syms, re.M) is not None
base = os.path.basename(lib)
c = ['// generated by gen-stub.py from ' + base, '#define _GNU_SOURCE', '#include <dlfcn.h>', '#include <jni.h>',
     '#include <limits.h>', '#include <stdio.h>', '#include <stdlib.h>', '#include <string.h>', '#include "pzldr.h"',
     'static void unfilled(void) { fprintf(stderr, "[pzldr] %s: native called before load\\n", "%s"); abort(); }' % ('%s', base),
     '#define N %d' % max(len(names), 1),
     '__attribute__((visibility("hidden"))) void *pz_slots[N] = { [0 ... N-1] = (void *)unfilled };',
     'static const char *const pz_names[N] = {' + (','.join('"%s"' % n for n in names) or '""') + '};',
     '__asm__(".text");']
for i, n in enumerate(names):
    c.append('__asm__(".globl %s\\n.type %s,%%function\\n%s:\\n adrp x16, pz_slots+%d\\n ldr x16, [x16, :lo12:pz_slots+%d]\\n br x16\\n");' % (n, n, n, 8*i, 8*i))
c.append('''
JNIEXPORT jint JNI_OnLoad(JavaVM *vm, void *reserved) {
    Dl_info di; char path[PATH_MAX];
    if (!dladdr((void *)JNI_OnLoad, &di) || !realpath(di.dli_fname, path)) return JNI_ERR;
    char *slash = strrchr(path, '/'); *slash = 0;
    char real[PATH_MAX + 64]; snprintf(real, sizeof real, "%s/android/%s", path, "BASE");
    void *h = pzldr_open(real);
    if (!h) return JNI_ERR;
    int missing = 0;
    for (int i = 0; i < N && pz_names[i][0]; i++) { void *f = pzldr_sym(h, pz_names[i]); if (f) pz_slots[i] = f; else missing++; }
    if (missing) fprintf(stderr, "[pzldr] BASE: %d exports missing\\n", missing);
    HAS_ONLOAD
    return JNI_VERSION_1_6;
}
'''.replace('BASE', base).replace('HAS_ONLOAD',
    '{ jint (*ol)(JavaVM *, void *) = (jint (*)(JavaVM *, void *))pzldr_sym(h, "JNI_OnLoad"); if (ol) return ol(vm, reserved); }' if has_onload else ''))
open(out, 'w').write('\n'.join(c) + '\n')
print(f'{base}: {len(names)} Java exports, JNI_OnLoad={has_onload}')
